# Helper Functions for Uncertainty Measures
# ============================================================================

def intersection_over_union(mask1, mask2):
    """Compute IoU for 2 binary masks.
    
    Args:
        mask1 (np.ndarray): First binary mask
        mask2 (np.ndarray): Second binary mask (must have same dimensions as mask1)
    
    Returns:
        float: Intersection over Union value (1.0 when both masks are empty)
    """
    intersection = np.sum(mask1 * mask2)
    union = np.sum(mask1 + mask2 - mask1 * mask2)
    if union == 0:
        return 1.0
    return intersection / union


def entropy_of_expected(probs, epsilon=1e-10):
    """Compute entropy of expected probabilities (voxel-level uncertainty).
    
    Args:
        probs (np.ndarray): Array of shape [num_models, num_voxels_X, num_voxels_Y, num_voxels_Z, num_classes]
        epsilon (float, optional): Small value to avoid -inf in logarithms. Defaults to 1e-10.
    
    Returns:
        np.ndarray: Voxel uncertainty map of shape [num_voxels_X, num_voxels_Y, num_voxels_Z]
    """
    mean_probs = np.mean(probs, axis=0)
    log_probs = -np.log(mean_probs + epsilon)
    return np.sum(mean_probs * log_probs, axis=-1)


def lesion_structural_uncertainty(cc_mask: np.ndarray, ens_pred_multi: np.ndarray):
    """Compute lesion structural uncertainty for a single connected component.
    
    Args:
        cc_mask (np.ndarray): Binary lesion mask, shape [H, W, D]
        ens_pred_multi (np.ndarray): Labeled lesion masks generated by an ensemble of models, shape [M, H, W, D]
    
    Returns:
        float: Lesion structural uncertainty value (1 - mean IoU across ensemble members)
    """
    def get_max_ious_ccmasks_ens(ens_multi):
        ens_ious_ = []
        for m in range(ens_multi.shape[0]):
            max_iou = 0.0
            for intersec_label in np.unique(cc_mask * ens_multi[m]):
                if intersec_label != 0.0:
                    lesion_m = (ens_multi[m] == intersec_label).astype(float)
                    iou = intersection_over_union(cc_mask, lesion_m)
                    if iou > max_iou:
                        max_iou = iou
            ens_ious_.append(max_iou)
        return ens_ious_

    # Lesion structural uncertainty measure
    # 1 - mean IoU of connected components on the ensemble's models prediction with cc_mask
    ens_ious = get_max_ious_ccmasks_ens(ens_pred_multi)
    
    return 1 - np.mean(ens_ious)


def plot_psu_distribution(psu_data: np.ndarray, new_psu_value: float, save_path: str, x_min=0, x_max=1):
    """Plot the new patient uncertainty value (PSU) with respect to PSU distribution.
    
    Args:
        psu_data (np.ndarray): An array of PSU values from the test population
        new_psu_value (float): The new PSU value to plot
        save_path (str): Path to save the plot
        x_min (int, optional): Minimum x-axis value. Defaults to 0.
        x_max (int, optional): Maximum x-axis value. Defaults to 1.
    """
    # Estimate PDF using kernel density estimation
    kde = stats.gaussian_kde(psu_data)

    # Create a range for plotting
    if x_min is None or x_max is None:
        x_min = min(psu_data) - (max(psu_data) - min(psu_data)) * 0.1
        x_max = max(psu_data) + (max(psu_data) - min(psu_data)) * 0.1
    x_plot = np.linspace(x_min, x_max, 500)
    pdf_values = kde(x_plot)

    # Calculate percentile
    percentile = stats.percentileofscore(psu_data, new_psu_value, kind='rank')

    # Plotting
    fig, ax = plt.subplots(figsize=(10, 4))

    # Plot the filled area under the curve
    ax.fill_between(x_plot, pdf_values, color='#D5EDD2', alpha=0.8)

    # Plot the curve itself
    ax.plot(x_plot, pdf_values, color='#76BF6A', linewidth=2)

    # Add the current_x marker
    current_x_pdf_value = kde(new_psu_value)[0]
    ax.plot(new_psu_value, current_x_pdf_value, marker='o', markersize=12, 
            color='#2BBAB7', linestyle='None', zorder=5)
    ax.annotate("", xy=(new_psu_value, current_x_pdf_value), 
                xytext=(new_psu_value, current_x_pdf_value * 1.5),
                fontsize=10, ha='center')

    # Customize axes
    ax.set_yticks([])
    ax.set_yticklabels([])
    ax.set_frame_on(False)

    # Set x-axis labels to min and max of data
    ax.set_xticks([np.floor(min(psu_data)), np.ceil(max(psu_data))])
    ax.set_xticklabels([f'{int(np.floor(min(psu_data)))}', f'{int(np.ceil(max(psu_data)))}'], 
                       fontsize=12, color='#666666')

    # Title with percentage
    ax.text(0.5, 1.05, f"{int(100 - percentile)} % of patients have higher uncertainty",
            transform=ax.transAxes, fontsize=20, color='#666666',
            ha='center', va='bottom')

    plt.tight_layout()
    if save_path is not None:
        plt.savefig(save_path)
    plt.close()


