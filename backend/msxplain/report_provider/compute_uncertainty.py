def compute_uncertainties(output_dir: str, n_samples: int, proba_threshold: float,
                         n_jobs: int = 4, l_min: int = 3, class_num: int = 1,
                         temperature: float = 1.0, probs: bool = True,
                         psu_data_filepath: str = None):
    """Compute uncertainties from NPZ ensemble predictions (programmatic API).
    
    Args:
        output_dir (str): Path to directory where uncertainties will be saved
        n_samples (int): Number of ensemble samples to use
        proba_threshold (float): Probability threshold for binary segmentation
        n_jobs (int, optional): Number of parallel workers. Defaults to 4.
        l_min (int, optional): Minimum lesion size - 1. Defaults to 3.
        class_num (int, optional): Class number for binary segmentation. Defaults to 1.
        temperature (float, optional): Temperature scaling for softmax. Defaults to 1.0.
        probs (bool, optional): Whether npz contains probabilities. Defaults to True.
        psu_data_filepath (str, optional): Path to CSV file with patient uncertainties for distribution plots.
    """
    np.random.seed(0)
    
    # Load a dataset of npz predictions
    npz_dataset = NpzDataset(pred_path=output_dir, pred_prefix='pred.npz')
    
    # Dataframe to save patient uncertainties
    pat_uncs_df = []
    
    # For each predicted npz file compute & save uncertainties
    for i_f in range(len(npz_dataset)):
        # Load data for a given patient
        data = npz_dataset[i_f]
        fn = data['filename']
        
        # Determine if we have probs or logits
        if 'pred_probs' in data:
            mems_prob = data['pred_probs'][:n_samples]  # [n_samples, H, W, D]
        elif 'pred_logits' in data:
            mems_prob = data['pred_logits'][:n_samples]
            if not probs:
                # Softmax probabilities for all models in ensemble
                mems_prob = np.stack([
                    special.softmax(s / temperature, axis=0)[class_num]
                    for s in mems_prob
                ], axis=0)
        else:
            raise ValueError(f"No 'pred_probs' or 'pred_logits' found in {fn}")
        
        assert len(mems_prob.shape) == 4, f"Expected 4D array, got shape {mems_prob.shape}"
        
        # Get the affine transformation matrix
        affine = data['affine']
        
        # Binary prediction mask from ensemble model
        ens_seg_bin = process_probs(
            prob_map=np.mean(mems_prob, axis=0),
            threshold=proba_threshold,
            l_min=l_min
        )
        
        # Save ensemble prediction
        ens_pred_file = os.path.join(output_dir, "pred.nii.gz")
        nib.Nifti1Image(ens_seg_bin.astype('float32'), affine=affine).to_filename(ens_pred_file)
        
        # Multi-labeled prediction mask from ensemble model
        ens_seg_lab = get_cc_mask(ens_seg_bin)
        
        # Labeled masks from each ensemble member
        mems_seg_bin = [
            process_probs(
                prob_map=ep,
                threshold=proba_threshold,
                l_min=l_min
            )
            for ep in mems_prob
        ]
        
        mems_seg_lab = np.stack(
            [get_cc_mask(ep) for ep in mems_seg_bin],
            axis=0
        )
        
        # Compute VOXEL uncertainty maps
        vox_uncs_mask = entropy_of_expected(
            np.concatenate(
                (np.expand_dims(mems_prob, axis=-1),
                 np.expand_dims(1. - mems_prob, axis=-1)),
                axis=-1
            )
        )
        
        # Save voxel uncertainty maps in nifti format
        vox_uncs_filepath = os.path.join(output_dir, "voxel_uncs.nii.gz")
        nib.Nifti1Image(vox_uncs_mask, affine=affine).to_filename(vox_uncs_filepath)
        
        # Compute LESION & PATIENT uncertainty maps
        if ens_seg_lab.sum() == 0:
            # No lesions predicted
            les_uncs_mask = np.zeros_like(ens_seg_lab, dtype='float32')
            pat_uncs_value = 0.0
            lesion_uncertainties = {}  # Empty dict for no lesions
            
            # Save empty lesion uncertainty map
            les_uncs_filepath = os.path.join(output_dir, "lesion_uncs.nii.gz")
            nib.Nifti1Image(les_uncs_mask, affine=affine).to_filename(les_uncs_filepath)
        else:
            cc_labels = np.unique(ens_seg_lab)
            cc_labels = cc_labels[cc_labels != 0.0]
            
            if len(cc_labels) > 0:
                with Parallel(n_jobs=n_jobs) as parallel_backend:
                    process = partial(lesion_structural_uncertainty, ens_pred_multi=mems_seg_lab)
                    
                    # Returns lists of float values, each corresponding to a connected component
                    les_uncs_list = parallel_backend(delayed(process)(
                        cc_mask=(ens_seg_lab == cc_label).astype("float")
                    ) for cc_label in cc_labels)
                
                # Create a mask and lesion uncertainties mapping
                les_uncs_mask = np.zeros_like(ens_seg_lab, dtype='float32')
                lesion_uncertainties = {}
                for cc_label, les_uncs_value in zip(cc_labels, les_uncs_list):
                    les_uncs_mask += les_uncs_value * (ens_seg_lab == cc_label).astype('float')
                    # Store lesion label and its uncertainty value
                    lesion_uncertainties[int(cc_label)] = float(les_uncs_value)
            else:
                les_uncs_mask = np.zeros_like(ens_seg_lab, dtype='float32')
                lesion_uncertainties = {}
            
            # Save lesion uncertainty maps in nifti format
            les_uncs_filepath = os.path.join(output_dir, "lesion_uncs.nii.gz")
            nib.Nifti1Image(les_uncs_mask, affine=affine).to_filename(les_uncs_filepath)
            
            # Compute PATIENT uncertainty as average IoU across ensemble members
            pat_uncs_value = 1 - np.mean([
                intersection_over_union(ens_seg_bin, mems_seg_bin[i]) 
                for i in range(n_samples)
            ])
        
        # Append patient and lesion uncertainties to the dataframe
        pat_uncs_df.append({
            "filename": fn,
            "PSU": pat_uncs_value,
            "lesion_uncertainties": lesion_uncertainties  # Maps lesion_label -> uncertainty_value
        })
        
        # Create a patient uncertainty plot if possible
        if psu_data_filepath is not None and pat_uncs_value > 0:
            try:
                # Read the data with patient uncertainties
                psu_data = pd.read_csv(psu_data_filepath, index_col=0)[["DSC-based mem_th", "set name", "hash"]]
                psu_data = psu_data[psu_data["set name"] != "ood"]["DSC-based mem_th"].values
                
                plot_psu_distribution(
                    psu_data=psu_data,
                    new_psu_value=pat_uncs_value,
                    save_path=os.path.join(output_dir, f"patient_uncertainty_distribution.png")
                )
            except Exception as e:
                logger.warning(f"Could not create PSU distribution plot for {fn}: {e}")
        
        # Save patient uncertainties dataframe after each patient is processed
        pd.DataFrame(pat_uncs_df).to_csv(
            os.path.join(output_dir, f"patient_uncs.csv")
        )
